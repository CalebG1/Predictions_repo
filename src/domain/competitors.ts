// --- Lookups / helpers ---

const competitorIndex = new Map(competitors.map((c) => [c.id, c]));
const moveByQuestion = new Map(competitorMoves.map((m) => [m.questionId, m]));

export function competitorById(id: string): Competitor | undefined {
  return competitorIndex.get(id);
}

export function moveForQuestion(questionId: string): CompetitorMove | undefined {
  return moveByQuestion.get(questionId);
}

export function competitorForQuestion(questionId: string): Competitor | undefined {
  const move = moveByQuestion.get(questionId);
  return move ? competitorIndex.get(move.competitorId) : undefined;
}

export function movesForCompetitor(competitorId: string): CompetitorMove[] {
  return competitorMoves.filter((m) => m.competitorId === competitorId);
}

export function isCompetitorQuestion(questionId: string): boolean {
  return moveByQuestion.has(questionId);
}
